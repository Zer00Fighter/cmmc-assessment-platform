from __future__ import annotations

from pathlib import Path

from openpyxl import Workbook, load_workbook

from src.workbook import WorkbookBuilder

ROOT = Path(__file__).resolve().parents[1]


def build_test_workbook(
    tmp_path: Path,
) -> Path:
    output_path = tmp_path / "CMMC_Assessment.xlsx"

    builder = WorkbookBuilder(
        project_root=ROOT,
        output_path=output_path,
    )

    result = builder.build()

    assert result == output_path

    return output_path


def load_test_workbook(
    tmp_path: Path,
):
    output_path = build_test_workbook(tmp_path)

    return load_workbook(
        output_path,
        data_only=False,
    )


def test_workbook_builder_creates_file(
    tmp_path: Path,
) -> None:
    output_path = build_test_workbook(tmp_path)

    assert output_path.exists()
    assert output_path.stat().st_size > 0


def test_atomic_save_replaces_existing_workbook(tmp_path: Path) -> None:
    output_path = tmp_path / "release.xlsx"
    output_path.write_bytes(b"previous release")
    builder = WorkbookBuilder(project_root=ROOT, output_path=output_path)
    workbook = Workbook()
    workbook.active["A1"] = "new release"

    builder._save_atomically(workbook)

    reopened = load_workbook(output_path)
    assert reopened.active["A1"].value == "new release"
    assert not list(tmp_path.glob(".release-*"))


