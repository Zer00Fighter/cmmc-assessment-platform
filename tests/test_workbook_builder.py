def test_partial_credit_requirements_are_configured(
    tmp_path: Path,
) -> None:
    workbook = load_test_workbook(tmp_path)

    worksheet = workbook["Assessment"]

    rows_by_requirement = {
        worksheet.cell(
            row=row,
            column=2,
        ).value: row
        for row in range(6, 116)
    }

    expected_partial_requirements = {
        "IA.L2-3.5.3",
        "SC.L2-3.13.11",
    }

    for requirement_id in expected_partial_requirements:
        row = rows_by_requirement[requirement_id]

        assert (
            worksheet.cell(
                row=row,
                column=8,
            ).value
            == "PARTIAL_3_OR_5"
        )

        assert (
            worksheet.cell(
                row=row,
                column=10,
            ).value
            == "NOT ASSESSED"
        )

        assert (
            worksheet.cell(
                row=row,
                column=11,
            ).value
            == "Yes"
        )

        assert (
            worksheet.cell(
                row=row,
                column=12,
            ).value
            == 5
        )

        assert worksheet.cell(
            row=row,
            column=20,
        ).value


